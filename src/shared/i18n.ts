export const STRINGS: Record<Language, Strings> = { en, es, fr }

export const stringsFor = (lang: Language): Strings => STRINGS[lang] ?? en

// The language to start with on first launch, from the computer's language.
export function detectLanguage(systemLocale: string): Language {
  const code = systemLocale.toLowerCase().slice(0, 2)
  return code === 'es' || code === 'fr' ? code : 'en'
}
